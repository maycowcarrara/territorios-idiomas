const indices = { pt: 0, en: 1, es: 2 };
const locais = { pt: "pt-BR", en: "en-US", es: "es-ES" };
export function detectarIdiomaPublico(languages = [], language = "") {
  const base = String(languages?.[0] || language || "pt")
    .toLowerCase()
    .split(/[-_]/)[0];
  return Object.hasOwn(indices, base) ? base : "pt";
}
export function criarIdiomaPublico(idioma = "pt") {
  const lingua = detectarIdiomaPublico([idioma]);
  const locale = locais[lingua];
  const t = (key, values = {}) => {
    const pluralKey =
      values.count === 1 && mensagensPublicas[`${key}One`] ? `${key}One` : key;
    const texto =
      mensagensPublicas[pluralKey]?.[indices[lingua]] ||
      mensagensPublicas[pluralKey]?.[0] ||
      key;
    return texto.replace(/\{(\w+)\}/g, (_, name) =>
      String(values[name] ?? `{${name}}`),
    );
  };
  return {
    lingua,
    locale,
    t,
    // Instants keep the territory's business timezone, independent of device timezone.
    formatarData: (value, comHora = false) =>
      new Intl.DateTimeFormat(locale, {
        timeZone: "America/Sao_Paulo",
        year: "numeric",
        month: "2-digit",
        day: "2-digit",
        ...(comHora
          ? { hour: "2-digit", minute: "2-digit", second: "2-digit" }
          : {}),
      }).format(new Date(value)),
    // A calendar date is not an instant: never parse it in the device timezone.
    formatarDia: (value) => {
      if (!/^\d{4}-\d{2}-\d{2}$/.test(value || "")) return "";
      const date = new Date(`${value}T12:00:00Z`);
      if (!Number.isFinite(+date) || date.toISOString().slice(0, 10) !== value)
        return "";
      return new Intl.DateTimeFormat(locale, {
        timeZone: "UTC",
        year: "numeric",
        month: "2-digit",
        day: "2-digit",
      }).format(date);
    },
    erro: (error) => {
      const mensagem = typeof error === "string" ? error : error?.message;
      const key = Object.keys(mensagensPublicas).find(
        (key) =>
          key.startsWith("error") && mensagensPublicas[key][0] === mensagem,
      );
      if (key) return t(key);
      if (error?.code === 429) return t("errorRate");
      if (error?.code === 410) return t("errorExpired");
      if (error?.code === 401 || error?.code === 403) return t("errorLink");
      if (error?.code === 503) return t("errorService");
      if (mensagem === mensagensPublicas.updatedNotice[0])
        return t("updatedNotice");
      return t("errorGeneric");
    },
    resumo: (done, total) => ({
      texto: t(
        done === total
          ? "summaryAll"
          : done === 0
            ? "summaryNone"
            : "summaryPartial",
        { done, total, pending: total - done },
      ),
      acao: t(
        done === total
          ? "confirmReturn"
          : done === 0
            ? "returnNone"
            : "returnPartial",
        { pending: total - done },
      ),
    }),
  };
}
